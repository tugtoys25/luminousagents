import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
function slugify(value: string): string {
  return (
    value
      .normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .replace(/&/g, ' and ')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 100) || 'opportunity'
  );
}

interface LegacyListing {
  id: string;
  number?: string;
  title: string;
  country?: string;
  price?: string;
  status?: string;
  points?: string[];
  body_html?: string;
  availability?: string;
}

const inputPath = resolve(process.argv[2] ?? 'legacy-source/mayfair/listings.json');
const outputPath = resolve(process.argv[3] ?? 'scripts/generated/legacy-opportunities.sql');

function sql(value: string | number | null): string {
  if (value === null) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  return `'${value.replace(/'/g, "''")}'`;
}

function lifecycle(status: string): string {
  const normalized = status.toUpperCase();
  if (normalized.includes('SOLD')) return 'sold';
  if (normalized.includes('OFF THE MARKET')) return 'off_market';
  if (normalized.includes('HOLD') || normalized.includes('UNDER OFFER')) return 'on_hold';
  return 'draft';
}

function safeText(value: unknown, maxLength: number): string {
  return typeof value === 'string' ? value.slice(0, maxLength) : '';
}

const parsed: unknown = JSON.parse(await readFile(inputPath, 'utf8'));
if (!Array.isArray(parsed)) throw new Error('Legacy listings source must be a JSON array.');
const records = parsed as LegacyListing[];
if (records.length !== 198)
  throw new Error(`Expected 198 legacy listings; found ${records.length}.`);
const ids = new Set<string>();
const slugs = new Set<string>();
const statements: string[] = [
  '-- Generated by scripts/import-legacy-listings.ts. Review content before publishing.',
];
const now = new Date().toISOString();
for (const [index, item] of records.entries()) {
  if (
    !item ||
    typeof item.id !== 'string' ||
    typeof item.title !== 'string' ||
    !item.title.trim()
  ) {
    throw new Error(`Invalid legacy listing at index ${index}.`);
  }
  if (ids.has(item.id)) throw new Error(`Duplicate legacy id: ${item.id}`);
  ids.add(item.id);
  const base = slugify(item.title);
  let slug = base;
  let suffix = 2;
  while (slugs.has(slug)) slug = `${base}-${suffix++}`;
  slugs.add(slug);
  const status = safeText(item.status, 80);
  const lifecycleStatus = lifecycle(status);
  const points = JSON.stringify(
    Array.isArray(item.points) ? item.points.map((p) => safeText(p, 1200)) : [],
  );
  const body = safeText(item.body_html, 30000);
  const summary = (Array.isArray(item.points) ? item.points[0] : '') || '';
  statements.push(
    `INSERT INTO opportunities (id, legacy_id, slug, title, country, opportunity_type, price_text, lifecycle, content_review_status, legacy_status, summary, body_html, availability, points_json, public_visibility, created_at, updated_at) VALUES (` +
      [
        sql(`legacy-${item.id}`),
        sql(item.id),
        sql(slug),
        sql(safeText(item.title, 300)),
        sql(safeText(item.country, 120) || null),
        sql(/hotel/i.test(item.title) ? 'casino-hotel' : 'casino'),
        sql(safeText(item.price, 120)),
        sql(lifecycleStatus),
        sql('pending'),
        sql(status),
        sql(safeText(summary, 1600)),
        sql(body),
        sql(safeText(item.availability, 200)),
        sql(points),
        '0',
        sql(now),
        sql(now),
      ].join(', ') +
      ") ON CONFLICT(legacy_id) DO UPDATE SET title=excluded.title, country=excluded.country, price_text=excluded.price_text, lifecycle=excluded.lifecycle, content_review_status='pending', legacy_status=excluded.legacy_status, summary=excluded.summary, body_html=excluded.body_html, availability=excluded.availability, points_json=excluded.points_json, public_visibility=0, updated_at=excluded.updated_at;",
  );
}
statements.push('');
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, statements.join('\n'), 'utf8');
console.log(
  `Generated ${records.length} records (${ids.size} unique IDs, ${slugs.size} unique slugs) at ${outputPath}. All records remain non-public until reviewed and explicitly published.`,
);
