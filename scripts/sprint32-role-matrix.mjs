#!/usr/bin/env node
/**
 * Sprint 32 — generate the staff role-by-route matrix from the source code.
 *
 *   node scripts/sprint32-role-matrix.mjs            # rewrite docs/ROLE_ROUTE_MATRIX.md
 *   node scripts/sprint32-role-matrix.mjs --check    # fail if the committed file is out of date
 *
 * Reads every `admin.<method>('<path>', requireRole(...))` registration in src/admin/routes.ts.
 * The router is mounted at /dashboard behind staffAuth(), so a route with no requireRole is open
 * to ANY signed-in staff role and is listed as such, so it cannot be missed in review.
 *
 * This is a static reading of the code. It does not replace a test that calls each route as
 * each role, and it does not describe record-level checks (a broker only seeing assigned rows).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'src/admin/routes.ts'), 'utf8');
const outPath = join(root, 'docs/ROLE_ROUTE_MATRIX.md');
const check = process.argv.includes('--check');

const ALL_ROLES = ['super_admin', 'admin', 'editor', 'broker', 'publisher', 'auditor'];

// Resolve `const xRoles = ['a', 'b'];` arrays declared in the file.
const named = {};
for (const match of source.matchAll(/^const (\w+Roles)\s*=\s*\[([^\]]*)\]/gm)) {
  named[match[1]] = [...match[2].matchAll(/'([a-z_]+)'/g)].map((m) => m[1]);
}

function resolveRoles(args) {
  const roles = new Set();
  for (const spread of args.matchAll(/\.\.\.(\w+)/g)) {
    const list = named[spread[1]];
    if (!list) throw new Error(`Unresolved role list ${spread[1]}`);
    list.forEach((r) => roles.add(r));
  }
  for (const literal of args.matchAll(/'([a-z_]+)'/g)) roles.add(literal[1]);
  return ALL_ROLES.filter((r) => roles.has(r));
}

const routes = [];
const pattern = /^admin\.(get|post|put|patch|delete)\(\s*(['"`])([^'"`]+)\2([\s\S]*?)(?:async\s*)?\(\s*c\s*\)\s*=>/gm;
for (const match of source.matchAll(pattern)) {
  const [, method, , path, middle] = match;
  const guard = /requireRole\(([^)]*)\)/.exec(middle);
  routes.push({
    method: method.toUpperCase(),
    path: `/dashboard${path === '/' ? '' : path}`,
    roles: guard ? resolveRoles(guard[1]) : null,
  });
}

const declared = (source.match(/^admin\.(get|post|put|patch|delete)\(/gm) ?? []).length;
if (routes.length !== declared) {
  console.error(`Parsed ${routes.length} of ${declared} admin routes; the parser needs updating.`);
  process.exit(1);
}

routes.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const cell = (roles, role) => (roles === null ? 'any' : roles.includes(role) ? 'yes' : '·');
const header = `| Method | Path | ${ALL_ROLES.join(' | ')} |`;
const divider = `| --- | --- | ${ALL_ROLES.map(() => '---').join(' | ')} |`;
const lines = routes.map(
  (r) => `| ${r.method} | \`${r.path}\` | ${ALL_ROLES.map((role) => cell(r.roles, role)).join(' | ')} |`,
);
const open = routes.filter((r) => r.roles === null);

const doc = `# Staff role-by-route matrix

Generated by \`node scripts/sprint32-role-matrix.mjs\` from \`src/admin/routes.ts\`. Do not edit by hand.

The dashboard router is mounted at \`/dashboard\` behind \`staffAuth()\`, so every route needs a signed-in staff
session. \`yes\` means the role is named in that route's \`requireRole(...)\`; \`·\` means it is refused;
\`any\` means the route has no \`requireRole\` and every signed-in staff role can call it.

This matrix describes route-level access only. Record-level rules (for example a broker seeing only
assigned records) are enforced inside the handlers and are covered by their own tests.

${routes.length} routes · ${open.length} open to any signed-in staff role.

${header}
${divider}
${lines.join('\n')}

## Routes open to any signed-in staff role

${open.length ? open.map((r) => `- \`${r.method} ${r.path}\``).join('\n') : 'None.'}

Review each one: a page shell that only renders static HTML is usually fine, but any route returning
data should name its roles explicitly.
`;

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== doc) {
    console.error('docs/ROLE_ROUTE_MATRIX.md is out of date. Run: node scripts/sprint32-role-matrix.mjs');
    process.exit(1);
  }
  console.log(`Role matrix is current (${routes.length} routes, ${open.length} open to any staff role).`);
} else {
  writeFileSync(outPath, doc);
  console.log(`Wrote docs/ROLE_ROUTE_MATRIX.md: ${routes.length} routes, ${open.length} open to any staff role.`);
}
